//! Replays the checked-in fuzz inputs through the harnesses on stable `cargo test`
//! (docs/process/testing.md §5.3, §5.5; WP-QA-08). No nightly, no cargo-fuzz, no libFuzzer runtime.
//!
//! * `fuzz/regressions/<target>/*`: minimized reproducers of earlier findings. Every file must
//!   pass; a failing file is a real bug (the fix comes after the red test, §5.5).
//! * `fuzz/corpus/<target>/*`: the seed corpus; replaying it also catches harnesses that rot.
//!
//! Consistency checks make sure a new target cannot be forgotten: the registry in
//! `ritsu_fuzz::harness::TARGETS`, `fuzz_targets/*.rs` and the `[[bin]]` list of `Cargo.toml`
//! must name the same targets, and no input directory may exist for an unknown target.

use ritsu_fuzz::harness::{Harness, TARGETS, find};
use std::collections::BTreeSet;
use std::fs;
use std::panic::{self, AssertUnwindSafe};
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Runs `harness` on `data`; the panic message becomes the error.
fn replay_bytes(harness: Harness, data: &[u8]) -> Result<(), String> {
    panic::catch_unwind(AssertUnwindSafe(|| harness(data))).map_err(|p| {
        if let Some(s) = p.downcast_ref::<String>() {
            s.clone()
        } else if let Some(s) = p.downcast_ref::<&str>() {
            (*s).to_owned()
        } else {
            "non-string panic payload".to_owned()
        }
    })
}

/// Sorted regular files directly inside `dir` (empty if it does not exist).
fn files_in(dir: &Path) -> Vec<PathBuf> {
    let Ok(rd) = fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut v: Vec<PathBuf> = rd
        .map(|e| e.expect("readable directory entry").path())
        .filter(|p| p.is_file())
        .collect();
    v.sort();
    v
}

/// Names of the sub-directories of `dir`.
fn subdirs_in(dir: &Path) -> BTreeSet<String> {
    let Ok(rd) = fs::read_dir(dir) else {
        return BTreeSet::new();
    };
    rd.map(|e| e.expect("readable directory entry").path())
        .filter(|p| p.is_dir())
        .map(|p| {
            p.file_name()
                .expect("file name")
                .to_string_lossy()
                .into_owned()
        })
        .collect()
}

/// Replays every file below `<root>/<kind>/<target>/`; returns the number of files and the failures.
fn replay_dir(kind: &str, target: &str, harness: Harness) -> (usize, Vec<String>) {
    let files = files_in(&root().join(kind).join(target));
    let mut failures = Vec::new();
    for f in &files {
        let data = fs::read(f).expect("readable input file");
        if let Err(msg) = replay_bytes(harness, &data) {
            let rel = f.strip_prefix(root()).unwrap_or(f).display().to_string();
            failures.push(format!(
                "{target}: {rel} ({} bytes): {msg}\n    reproduce: cargo +nightly fuzz run {target} fuzz/{rel}",
                data.len()
            ));
        }
    }
    (files.len(), failures)
}

fn replay_all(kind: &str) -> usize {
    let mut total = 0;
    let mut failures = Vec::new();
    for (target, harness) in TARGETS {
        let (n, mut f) = replay_dir(kind, target, *harness);
        total += n;
        failures.append(&mut f);
    }
    assert!(
        failures.is_empty(),
        "{} of {total} replayed {kind} input(s) failed:\n  {}",
        failures.len(),
        failures.join("\n  ")
    );
    total
}

#[test]
fn regressions_replay_clean() {
    let n = replay_all("regressions");
    eprintln!("replayed {n} regression input(s)");
}

#[test]
fn corpus_replays_clean() {
    let n = replay_all("corpus");
    // The seed corpus is generated by tools/gen_seeds.py; an empty one means a path or generator bug.
    assert!(n > 0, "no corpus inputs found below fuzz/corpus/");
    eprintln!("replayed {n} corpus input(s)");
}

#[test]
fn every_input_directory_belongs_to_a_known_target() {
    for kind in ["regressions", "corpus"] {
        for d in subdirs_in(&root().join(kind)) {
            assert!(
                find(&d).is_some(),
                "fuzz/{kind}/{d}/ has no harness in ritsu_fuzz::harness::TARGETS: its inputs would never be replayed"
            );
        }
    }
}

/// Target names listed in the registry, `fuzz_targets/*.rs` and `[[bin]]` entries.
#[test]
fn registry_target_files_and_manifest_agree() {
    let registry: BTreeSet<String> = TARGETS.iter().map(|(n, _)| (*n).to_owned()).collect();
    assert_eq!(registry.len(), TARGETS.len(), "duplicate name in TARGETS");

    let files: BTreeSet<String> = files_in(&root().join("fuzz_targets"))
        .iter()
        .filter(|p| p.extension().is_some_and(|e| e == "rs"))
        .map(|p| p.file_stem().expect("stem").to_string_lossy().into_owned())
        .collect();
    assert_eq!(registry, files, "TARGETS vs fuzz_targets/*.rs");

    let manifest = fs::read_to_string(root().join("Cargo.toml")).expect("Cargo.toml");
    let bins: BTreeSet<String> = manifest
        .lines()
        .filter_map(|l| l.trim().strip_prefix("name = \""))
        .filter_map(|l| l.strip_suffix('"'))
        .filter(|n| n.starts_with("fuzz_"))
        .map(str::to_owned)
        .collect();
    assert_eq!(registry, bins, "TARGETS vs [[bin]] entries in Cargo.toml");

    // Each target file must forward to its own harness (guards copy-paste errors).
    for name in &registry {
        let src = fs::read_to_string(root().join("fuzz_targets").join(format!("{name}.rs")))
            .expect("target file");
        let module = name.strip_prefix("fuzz_").expect("fuzz_ prefix");
        assert!(
            src.contains(&format!("ritsu_fuzz::harness::{module}::run(data)")),
            "{name}.rs does not call ritsu_fuzz::harness::{module}::run"
        );
    }
}

// Self-tests of the replay machinery: "green" must mean something.

#[test]
fn replay_reports_a_panicking_harness() {
    fn bad(data: &[u8]) {
        assert!(data.len() < 3, "too long: {}", data.len());
    }
    assert!(replay_bytes(bad, &[1, 2]).is_ok());
    let err = replay_bytes(bad, &[1, 2, 3]).expect_err("must report the panic");
    assert!(err.contains("too long: 3"), "{err}");
}

/// The regression for the MmioBus alignment finding is a known reproducer: the harness must
/// still be able to tell a broken bus from a good one, so check it actually executes the input.
#[test]
fn mmio_regression_input_is_present_and_exercised() {
    let files = files_in(&root().join("regressions").join("fuzz_mmio_bus"));
    assert!(
        !files.is_empty(),
        "fuzz/regressions/fuzz_mmio_bus/ lost its reproducer"
    );
    let harness = find("fuzz_mmio_bus").expect("harness registered");
    for f in files {
        let data = fs::read(&f).expect("readable");
        replay_bytes(harness, &data).unwrap_or_else(|m| panic!("{}: {m}", f.display()));
    }
}
